class ContactModel {
  final String name;
  final String year;
  final String email;
  final String phone;
  final String github;
  final String location;
  final String linkedIn;
  ContactModel({
    required this.name,
    required this.year,
    required this.email,
    required this.phone,
    required this.github,
    required this.location,
    required this.linkedIn,
  });
}
